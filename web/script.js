// El HTML ya viene en español (lo que leen Google y las vistas previas de
// WhatsApp); el inglés se aplica si la persona lo elige y se recuerda.
let currentLang = "es";

function readSavedLang() {
  try { return localStorage.getItem(LANG_STORAGE_KEY); } catch { return null; }
}

function saveLang(lang) {
  try { localStorage.setItem(LANG_STORAGE_KEY, lang); } catch { /* modo privado: no se recuerda */ }
}

function applyLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  const dictionary = translations[lang];
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dictionary[key] !== undefined) el.textContent = dictionary[key];
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const key = el.getAttribute("data-i18n-html");
    if (dictionary[key] !== undefined) el.innerHTML = dictionary[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dictionary[key] !== undefined) el.setAttribute("placeholder", dictionary[key]);
  });
  document.title = PAGE_META[lang].title;
  document.getElementById("meta-description").setAttribute("content", PAGE_META[lang].description);
  document.querySelectorAll(".lang-pill").forEach((el, i) => el.classList.toggle("active", (lang === "es" && i === 0) || (lang === "en" && i === 1)));
  renderWaitlistStatus();
}

document.getElementById("language-toggle").addEventListener("click", () => {
  const next = currentLang === "es" ? "en" : "es";
  saveLang(next);
  applyLanguage(next);
});

