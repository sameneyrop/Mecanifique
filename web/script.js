const waitlistForm = document.getElementById("waitlist-form");
const waitlistStatusEl = document.getElementById("waitlist-status");
const waitlistSubmit = document.getElementById("waitlist-submit");
// El servidor regresa a esta página con ?registro=ok o ?registro=error.
const waitlistResult = new URLSearchParams(window.location.search).get("registro");

function renderWaitlistStatus() {
  if (!waitlistStatusEl) return;
  if (waitlistResult !== "ok" && waitlistResult !== "error") {
    waitlistStatusEl.hidden = true;
    return;
  }
  waitlistStatusEl.hidden = false;
  waitlistStatusEl.className = `form-status ${waitlistResult}`;
  waitlistStatusEl.textContent = translations[currentLang][`waitlist.${waitlistResult}`];
}

if (waitlistResult === "ok" || waitlistResult === "error") {
  // Quita ?registro= de la dirección para que recargar no repita el mensaje.
  history.replaceState(null, "", `${window.location.pathname}#lista`);
}

// "Avísame" y "Quiero unirme como mecánico" dejan elegido el tipo de registro.
document.querySelectorAll("a[data-role]").forEach(link => {
  link.addEventListener("click", () => {
    const radio = waitlistForm && waitlistForm.querySelector(`input[name="role"][value="${link.dataset.role}"]`);
    if (radio) radio.checked = true;
  });
});

if (waitlistForm) {
  waitlistForm.addEventListener("submit", () => {
    // El servidor puede tardar unos segundos si estaba en reposo.
    waitlistSubmit.disabled = true;
    waitlistSubmit.textContent = translations[currentLang]["waitlist.sending"];
  });
}

// Al volver con el botón "atrás" del navegador, el botón no debe quedar trabado.
window.addEventListener("pageshow", () => {
  if (!waitlistSubmit) return;
  waitlistSubmit.disabled = false;
  waitlistSubmit.textContent = translations[currentLang]["waitlist.submit"];
});

const observer = new IntersectionObserver((entries) => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      entry.target.classList.add("in-view");
      observer.unobserve(entry.target);
    }
  });
}, {threshold: 0.16});
document.querySelectorAll(".reveal").forEach(el => observer.observe(el));

const progressBar = document.getElementById("progress-bar");
function updateProgress() {
  const scrollTop = window.scrollY;
  const scrollable = document.documentElement.scrollHeight - window.innerHeight;
  progressBar.style.width = scrollable > 0 ? `${(scrollTop / scrollable) * 100}%` : "0%";
}
window.addEventListener("scroll", updateProgress, {passive:true});
updateProgress();

const parallaxEls = document.querySelectorAll("[data-parallax]");
function updateParallax() {
  const vh = window.innerHeight;
  parallaxEls.forEach(el => {
    const rect = el.getBoundingClientRect();
    const amount = parseFloat(el.dataset.parallax || "0.04");
    const center = rect.top + rect.height/2;
    const offset = (vh/2 - center) * amount;
    el.style.transform = `translate3d(0, ${offset}px, 0)`;
  });
}
window.addEventListener("scroll", updateParallax, {passive:true});
window.addEventListener("resize", updateParallax);
updateParallax();

document.querySelectorAll(".tilt-card").forEach(card => {
  card.addEventListener("pointermove", e => {
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
    const rect = card.getBoundingClientRect();
    const x = (e.clientX - rect.left) / rect.width - .5;
    const y = (e.clientY - rect.top) / rect.height - .5;
    card.style.transform = `perspective(1000px) rotateX(${(-y*5).toFixed(2)}deg) rotateY(${(x*6).toFixed(2)}deg) translateY(-2px)`;
  });
  card.addEventListener("pointerleave", () => {
    card.style.transform = "";
  });
});

document.querySelectorAll(".magnetic").forEach(btn => {
  btn.addEventListener("pointermove", e => {
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
    const rect = btn.getBoundingClientRect();
    const x = (e.clientX - (rect.left + rect.width/2)) * .08;
    const y = (e.clientY - (rect.top + rect.height/2)) * .08;
    btn.style.transform = `translate(${x}px, ${y}px)`;
  });
  btn.addEventListener("pointerleave", () => {
    btn.style.transform = "";
  });
});

